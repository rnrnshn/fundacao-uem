import { expect, test } from '@playwright/test'

test('scroll reveals, hero transitions and dialogs remain interactive', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.locator('.page-transition')).toHaveCSS('animation-name', 'page-enter')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  const reveal = page.locator('[data-motion="pending"]').first()
  await expect(reveal).toBeAttached()
  const handle = await reveal.elementHandle()
  await reveal.scrollIntoViewIfNeeded()
  await expect.poll(() => handle!.getAttribute('data-motion')).toBe('visible')
  await expect.poll(() => handle!.evaluate(node => getComputedStyle(node).opacity)).toBe('1')
  await page.getByRole('button', { name: 'Ver destaque 2', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('O melhor da terra')
  await expect(page.locator('.hero-slide-image[data-active="true"]')).toHaveCount(1)
  await expect(page.locator('.hero-slide-image[data-active="true"]')).toHaveCSS('opacity', '1')
  await page.getByRole('button', { name: 'Ver detalhes: Tomate fresco', exact: true }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCSS('animation-name', 'dialog-enter')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
})

test('reduced motion removes animations without hiding content or controls', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.page-transition')).toHaveCSS('animation-name', 'none')
  await expect(page.locator('[data-motion="pending"]')).toHaveCount(0)
  await expect(page.locator('.hero-slide-image').first()).toHaveCSS('transition-duration', '0s')
  await page.getByRole('button', { name: 'Ver destaque 3', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Uma nova geração')
  const products = page.getByRole('region', { name: 'Produtos em destaque', exact: true })
  await products.getByRole('button', { name: 'Próximos produtos' }).click()
  await expect.poll(() => products.locator('.product-track').evaluate(node => node.scrollLeft)).toBeGreaterThan(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Abrir menu' }).click()
  await expect(page.getByRole('navigation', { name: 'Navegação principal' })).toBeVisible()
  await page.getByRole('button', { name: 'Fechar menu' }).click()
  await expect(page.getByRole('navigation', { name: 'Navegação principal' })).not.toBeVisible()
})

test('motion preference changes reveal pending content and SSR needs no animation script', async ({ page, browser }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.locator('[data-motion="pending"]').first()).toBeAttached()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('[data-motion="pending"]')).toHaveCount(0)
  const context = await browser.newContext({ javaScriptEnabled: false })
  const staticPage = await context.newPage()
  await staticPage.goto('http://127.0.0.1:4320/')
  await expect(staticPage.getByRole('heading', { name: 'Produtos em destaque', exact: true })).toBeVisible()
  await expect(staticPage.locator('[data-motion="pending"]')).toHaveCount(0)
  await context.close()
})
